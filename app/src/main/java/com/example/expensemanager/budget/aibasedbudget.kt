@Composable
fun AIBasedBudgetScreen(userId: String, db: FirebaseFirestore, onBudgetSet: () -> Unit) {
    var salary by remember { mutableStateOf("") }
    var budgetGenerated by remember { mutableStateOf(false) }
    var showSalaryInput by remember { mutableStateOf(false) }
    var categoryBudget by remember { mutableStateOf<Map<String, Double>?>(null) }
    val context = LocalContext.current

    LaunchedEffect(Unit) {
        // Check if salary is already set
        val userRef = db.collection("users").document(userId)
        val userSnapshot = userRef.get().await()
        val userSalary = userSnapshot.getString("salary")
        if (userSalary == null) {
            showSalaryInput = true
        } else {
            salary = userSalary
        }
    }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .padding(16.dp),
        horizontalAlignment = Alignment.CenterHorizontally,
        verticalArrangement = Arrangement.Center
    ) {
        Text(
            text = "AI Based Budget",
            fontSize = 30.sp,
            fontWeight = FontWeight.Bold,
            color = MaterialTheme.colorScheme.primary
        )

        Spacer(modifier = Modifier.height(20.dp))

        // If salary is not set, show input field
        if (showSalaryInput) {
            OutlinedTextField(
                value = salary,
                onValueChange = { salary = it },
                label = { Text("Enter your Salary") },
                modifier = Modifier.fillMaxWidth()
            )

            Spacer(modifier = Modifier.height(16.dp))

            Button(onClick = {
                if (salary.isNotEmpty()) {
                    saveSalaryToFirebase(userId, salary, db) {
                        Toast.makeText(context, "Salary saved!", Toast.LENGTH_SHORT).show()
                        showSalaryInput = false
                    }
                }
            }) {
                Text("Save Salary")
            }

        } else {
            Text(text = "Current Salary: $salary")
            Spacer(modifier = Modifier.height(16.dp))

            Button(onClick = {
                showSalaryInput = true // Allow changing the salary
            }) {
                Text("Change Salary")
            }

            Spacer(modifier = Modifier.height(20.dp))

            Button(onClick = {
                generateAIBasedBudget(userId, salary.toDouble(), context,FirebaseFirestore.getInstance()) { budget ->
                    categoryBudget = budget
                    budgetGenerated = true
                }
            }) {
                Text("Generate Budget")
            }

            Spacer(modifier = Modifier.height(20.dp))

            if (budgetGenerated && categoryBudget != null) {
                Text(text = "Category-wise Budget:", fontWeight = FontWeight.Bold)
                Spacer(modifier = Modifier.height(8.dp))

                categoryBudget!!.forEach { (category, amount) ->
                    Text("$category: ₹${amount.format()}")
                }

                Spacer(modifier = Modifier.height(20.dp))

                Button(onClick = {
                    categoryBudget!!.forEach { (category, amount) ->
                        saveAiLimit(context, category, amount, "monthly", userId)
                    }
                    onBudgetSet() // Call the callback after budget is set
                }) {
                    Text("Save Budget")
                }
            }
        }
    }
}

fun saveSalaryToFirebase(userId: String, salary: String, db: FirebaseFirestore, onComplete: () -> Unit) {
    val userRef = db.collection("users").document(userId)
    userRef.update("salary", salary)
        .addOnSuccessListener {
            onComplete()
        }
        .addOnFailureListener { e ->
            println("Error saving salary: ${e.message}")
        }
}


fun generateAIBasedBudget(
    userId: String,
    salary: Double,
    context: Context, // Pass context here
    db: FirebaseFirestore,
    onBudgetGenerated: (Map<String, Double>) -> Unit
) {
    // Fetch income and expenses data from Firebase
    db.collection("users").document(userId).collection("transactions")
        .get()
        .addOnSuccessListener { result ->
            val income = mutableListOf<Double>()
            val expenses = mutableListOf<Double>()

            // Process Firebase data to get user transactions
            for (document in result) {
                val type = document.getString("type") ?: continue
                val amount = document.getDouble("amount") ?: continue

                if (type == "income") {
                    income.add(amount)
                } else if (type == "expense") {
                    expenses.add(amount)
                }
            }

            // Calculate total income and expenses
            val totalIncome = income.sum()
            val totalExpenses = expenses.sum()

            // Prepare the input for TensorFlow Lite
            val inputTensor = prepareInputTensor(salary, totalIncome, totalExpenses)

            // Run TensorFlow Lite model for budget prediction
            val predictedBudget = runModelInference(context, inputTensor)

            // Post-process TensorFlow Lite output into categories
            val budget = postProcessOutput(predictedBudget)

            // Pass the predicted budget to the callback
            onBudgetGenerated(budget)
        }
        .addOnFailureListener { e ->
            // Show error message using Toast
            Toast.makeText(context, "Error fetching user data: ${e.message}", Toast.LENGTH_SHORT).show()
        }
}


// Prepare the input for TensorFlow Lite model
fun prepareInputTensor(salary: Double, income: Double, expenses: Double): ByteBuffer {
    val inputBuffer = ByteBuffer.allocateDirect(3 * 4) // 3 floats (salary, income, expenses)
    inputBuffer.order(ByteOrder.nativeOrder())
    inputBuffer.putFloat(salary.toFloat())
    inputBuffer.putFloat(income.toFloat())
    inputBuffer.putFloat(expenses.toFloat())
    return inputBuffer
}



fun loadModelFile(context: Context, modelFileName: String): ByteBuffer {
    val assetManager = context.assets
    val inputStream = assetManager.open(modelFileName)
    val byteArray = inputStream.readBytes()
    val byteBuffer = ByteBuffer.allocateDirect(byteArray.size)
    byteBuffer.put(byteArray)
    byteBuffer.order(ByteOrder.nativeOrder())
    return byteBuffer
}

// Update runModelInference to accept Context
fun runModelInference(context: Context, inputBuffer: ByteBuffer): FloatArray {
    return try {
        // Load the TensorFlow Lite model using the context
        val tfliteModel = loadModelFile(context, "budget.tflite")

        // Allocate output buffer (assuming 9 categories)
        val outputBuffer = Array(1) { FloatArray(9) } // 1 output, 9 categories

        // Initialize TensorFlow Lite interpreter
        val tfliteInterpreter = Interpreter(tfliteModel)

        // Run the inference
        tfliteInterpreter.run(inputBuffer, outputBuffer)

        // Return the output (budget for each category)
        outputBuffer[0]
    } catch (e: Exception) {
        // Log the exception (or handle it accordingly)
        e.printStackTrace()
        FloatArray(9) // Return an array of zeros or handle error appropriately
    }
}




// Post-process the model's output into meaningful categories
fun postProcessOutput(outputArray: FloatArray): Map<String, Double> {
    // These are your specified categories
    val categories = listOf(
        "housing", "food", "entertainment", "transportation", "investment",
        "healthcare", "bills", "subscription", "others"
    )

    // Pair categories with predicted values
    return categories.zip(outputArray.map { it.toDouble() }).toMap()
}
fun saveAiLimit(context: Context, category: String, amount: Double, type: String, userId: String) {
    val firestore = FirebaseFirestore.getInstance()
    val limitData = hashMapOf(
        "category" to category,
        "amount" to amount,
        "type" to type
    )
    firestore.collection("users")
        .document(userId)
        .collection("limits")
        .add(limitData)
        .addOnSuccessListener {
            Toast.makeText(context, "$category limit saved successfully", Toast.LENGTH_SHORT).show()
        }
        .addOnFailureListener { e ->
            Toast.makeText(context, "Error saving limit: ${e.message}", Toast.LENGTH_SHORT).show()
        }
}
